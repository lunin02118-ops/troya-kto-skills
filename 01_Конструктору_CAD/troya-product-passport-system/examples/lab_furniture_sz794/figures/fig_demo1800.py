"""Рисунки для столов демонстрационных 1800×750×900: поз. 1 — химия (СтLABGr1800G-04, мойка и смеситель),
поз. 2 — физика (СтLABGr1800G-03, передняя панель между тумбами со щитком и розеткой): рисунок 1 «Общий вид»,
рисунок 2 «Схема монтажа» (разнесённый вид), у поз. 1 — рисунок 3 «Подключение мойки и смесителя»; обложка.
Геометрия — по КД заказа 794: сборочный чертёж каркаса СДЛ 000 (С-образные опоры из трубы 60×30×1,5: стойка 875,
плечи 600, ширина по опорам 1690, перемычка 1630 между верхними углами стоек), эскиз заказчика «Стол демонстрационный
кабинет химии» и схема сборки 03_Корпус\\02_Схемы сборки (тумбы 452×547, царга 1627×871, бортики 1764×73 и 502×72,
мойка 300×150, смеситель двухрожковый). Сторона преподавателя (двери тумб) — y = 0, сторона учащихся
(стойки опор, царга, продольный бортик) — y = 750. Мойка — над левой тумбой (со стороны преподавателя).
Поз. 2: панель передняя 725×206 между тумбами под столешницей; на ней по схеме сборки щиток у правой тумбы,
рядом розетка двойная с крышкой — расположение подтверждает конструктор.
Запуск: python -P fig_demo1800.py <папка вывода>
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fig_atom1200 import LEGS, bracket          # кронштейн крепления к полу — общий со столами «Атом»
from iso import Drawing, box, extrude, rounded_rect, translate
from sch import Sheet

L, D, H = 1800, 750, 900
T_TOP = 16
Z_TOP = H - T_TOP                     # низ столешницы
SUP = [(55, 85), (1715, 1745)]        # опоры по x (труба 60×30, сторона 30 вдоль x)
YF = (75, 675)                        # плечи опор 600 мм
YP = (YF[1] - 60, YF[1])              # стойка опоры — со стороны учащихся
Z_FOOT = 10                           # высота регулируемой опоры под плечом (как у «Атома»)
YO = (YF[0] + 30, YF[1] - 30)         # оси регулируемых опор
TUMBA = [(86, 538), (1262, 1714)]     # тумбы 452 мм: левая — под мойкой, правая — с ящиком
YT = (52, 599)                        # корпус тумбы 547 мм
ZT = (27, 866)                        # на ножках 27 мм, боковины 839
YC = (599, 615)                       # царга 16 мм за тумбами
SINK = (236, 386, 220, 520)           # мойка 150 (x) × 300 (y): x0, x1, y0, y1
MIX = (311, 610)                      # ось смесителя
PANEL = (538, 1262, 70, 86, 678, Z_TOP)    # поз. 2: панель передняя 725×206: x0, x1, y0, y1, z0, z1
SHIELD = (1110, 1240, 22, 70, 690, 850)   # щиток на 4 модуля на лицевой стороне панели
SOCKET = (950, 1090, 30, 70, 730, 800)    # розетка накладная двойная с крышкой


def rib_side(x0):
    """Боковой бортик 502×72 мм со скруглением R50 переднего верхнего угла, ЛДСП 16."""
    y0, y1, z0, z1, r = D - 502, D, H, H + 72, 50
    pts = [(x0, y0, z0), (x0, y1, z0), (x0, y1, z1)]
    for i in range(11):
        a = math.radians(90 + 90 * i / 10)
        pts.append((x0, y0 + r + r * math.cos(a), z1 - r + r * math.sin(a)))
    return extrude(pts, (16, 0, 0), "бортик боковой")


def rect_lines(x0, x1, y0, y1, z):
    p = [(x0, y0, z), (x1, y0, z), (x1, y1, z), (x0, y1, z)]
    return [("l", p[i], p[(i + 1) % 4]) for i in range(4)]


def sink_top():
    """Вид мойки на столешнице: борт, чаша и слив (узор верхней грани)."""
    x0, x1, y0, y1 = SINK
    return (rect_lines(x0 - 6, x1 + 6, y0 - 6, y1 + 6, H) + rect_lines(x0 + 8, x1 - 8, y0 + 8, y1 - 8, H)
            + [("dot", ((x0 + x1) / 2, (y0 + y1) / 2, H), 8)])


def mixer(x=MIX[0], y=MIX[1], H=H):
    """Смеситель двухрожковый на плоскости z = H: корпус, стойка, излив (к −y), два вентиля."""
    return [box(x - 20, y - 15, H, x + 20, y + 15, H + 35, "смеситель"),
            box(x - 6, y - 6, H + 35, x + 6, y + 6, H + 168, "смеситель"),
            box(x - 6, y - 140, H + 168, x + 6, y + 6, H + 180, "смеситель"),
            box(x - 6, y - 140, H + 128, x + 6, y - 128, H + 168, "смеситель"),
            box(x - 58, y - 6, H + 14, x - 20, y + 6, H + 26, "смеситель"),
            box(x + 20, y - 6, H + 14, x + 58, y + 6, H + 26, "смеситель"),
            box(x - 64, y - 12, H + 26, x - 52, y + 12, H + 32, "смеситель"),
            box(x + 52, y - 12, H + 26, x + 64, y + 12, H + 32, "смеситель")]


def parts(chem=True):
    """Тела в собранном положении, сгруппированные для разнесённого вида; chem — поз. 1 (мойка), иначе поз. 2."""
    g = {k: [] for k in ("frame", "feet", "brackets", "tumba_l", "tumba_r", "panel", "top", "rim_long", "rim_l",
                         "rim_r", "sink", "mixer", "front")}
    for (x0, x1), s in zip(SUP, (-1, 1)):     # полка кронштейна наружу: внутри опор стоят тумбы
        xc = (x0 + x1) / 2
        g["frame"] += [box(x0, YF[0], Z_FOOT, x1, YF[1], Z_FOOT + 60, "опора"),
                       box(x0, YF[0], Z_TOP - 60, x1, YF[1], Z_TOP, "опора"),
                       box(x0, YP[0], Z_FOOT + 60, x1, YP[1], Z_TOP - 60, "опора")]
        for yo in YO:
            g["feet"].append(box(xc - 12, yo - 12, 0, xc + 12, yo + 12, Z_FOOT, "опора регулируемая", line=0.7))
            g["brackets"].append(bracket(xc, yo, s))
    g["frame"].append(box(SUP[0][1], YP[1] - 30, Z_TOP - 60, SUP[1][0], YP[1], Z_TOP, "перемычка"))
    for k, (x0, x1) in zip(("tumba_l", "tumba_r"), TUMBA):
        t = g[k]
        t.append(box(x0, YT[0], ZT[0], x1, YT[1], ZT[1], "тумба"))
        for xl in (x0 + 30, x1 - 60):
            for yl in (YT[0] + 30, YT[1] - 60):
                t.append(box(xl, yl, 0, xl + 30, yl + 30, ZT[0], "ножка", line=0.7))
        xc = (x0 + x1) / 2
        fronts = [(45, 832)] if k == "tumba_l" else [(45, 690), (694, 834)]
        for z0, z1 in fronts:
            t.append(box(x0 + 2, YT[0] - 16, z0, x1 - 2, YT[0], z1, "дверца"))
            zh = z1 - 52 if z1 - z0 > 200 else (z0 + z1) / 2 - 6
            t.append(box(xc - 50, YT[0] - 26, zh, xc + 50, YT[0] - 16, zh + 12, "ручка", line=0.7))
    g["panel"].append(box(SUP[0][1] + 1, YC[0], 13, SUP[1][0] - 1, YC[1], Z_TOP, "царга"))
    g["top"].append(extrude(rounded_rect(0, 0, L, D, Z_TOP, r_front=50), (0, 0, T_TOP), "столешница",
                            sink_top() if chem else None))
    g["rim_long"].append(box(16, D - 16, H, L - 16, D, H + 73, "бортик продольный"))
    g["rim_l"].append(rib_side(0))
    g["rim_r"].append(rib_side(L - 16))
    if chem:
        x0, x1, y0, y1 = SINK
        g["sink"] += [box(x0 - 6, y0 - 6, H, x1 + 6, y1 + 6, H + 3, "мойка"),
                      box(x0, y0, H - 150, x1, y1, H, "мойка")]
        g["mixer"] += mixer()
    else:
        x0, x1, y0, y1, z0, z1 = PANEL
        g["front"].append(box(x0, y0, z0, x1, y1, z1, "панель передняя"))
        x0, x1, y0, y1, z0, z1 = SHIELD                  # щиток: корпус и дверца
        door = [(x0 + 12, y0, z0 + 25), (x1 - 12, y0, z0 + 25), (x1 - 12, y0, z1 - 25), (x0 + 12, y0, z1 - 25)]
        g["front"].append(box(x0, y0, z0, x1, y1, z1, "щиток",
                              {"front": [("l", door[i], door[(i + 1) % 4]) for i in range(4)]}))
        x0, x1, y0, y1, z0, z1 = SOCKET                  # розетка: две крышки
        xm = (x0 + x1) / 2
        g["front"].append(box(x0, y0, z0, x1, y1, z1, "розетка двойная",
                              {"front": [("l", (xm, y0, z0 + 6), (xm, y0, z1 - 6))]}))
    return g


def general(chem=True):
    """Рисунок 1: со стороны преподавателя справа, как изометрия схемы сборки."""
    g = parts(chem)
    if chem:
        del g["sink"][1]                   # чаша мойки скрыта в тумбе — на виде только борт на столешнице
    d = Drawing(116, 84, view="спереди-справа")
    for items in g.values():
        d.add(*items)
    d.callout(1, (1745, 400, Z_FOOT + 30), (12, -6))
    d.callout(2, (1250, 300, H), (16, 12))
    d.callout(3, (300, YT[0] - 16, 400), (-16, -8))
    d.callout(4, (1488, YT[0] - 16, 380), (-10, -16))
    d.callout(5, (620, YC[0], 150 if chem else 60), (-6, -14) if chem else (-8, -10))   # царга в просвете между тумбами
    if chem:
        d.callout(6, (311, 400, H), (-18, -3))
        d.callout(7, (MIX[0], MIX[1], H + 170), (-12, 8))
        nf, nb = 8, 9
    else:
        d.callout(6, (700, PANEL[2], 720), (-22, -4))
        d.callout(7, (SHIELD[0] + 20, SHIELD[2], 760), (4, 22))
        d.callout(8, ((SOCKET[0] + SOCKET[1]) / 2, SOCKET[2], 750), (-20, -10))
        nf, nb = 10, 11
    d.callout(nf, (1730, YO[0], 4), (10, -6))
    d.callout(nb, (1700, YO[1] - 12, 1), (18, -2))
    return d


def mounting(chem=True):
    """Рисунок 2: разнесённый вид — каркас, тумбы и царга, столешница с бортиками, мойка и смеситель (поз. 1)
    или передняя панель со щитком и розеткой (поз. 2)."""
    g = parts(chem)
    up = 420
    off = {"frame": (0, 0, 0), "feet": (0, 0, -100), "brackets": (0, 0, -50), "tumba_l": (0, -420, 0),
           "tumba_r": (0, -420, 0), "panel": (0, 260, 0), "top": (0, 0, up), "rim_long": (0, 0, up + 170),
           "rim_l": (-200, 0, up + 120), "rim_r": (200, 0, up + 120), "sink": (0, 0, up + 300),
           "mixer": (0, 0, up + 470), "front": (0, -420, 0)}
    d = Drawing(116, 100, view="спереди-справа")
    for k, items in g.items():
        d.add(*[translate(s, off[k]) for s in items])
    ax = "dashdot"
    for x in (70, 1730):                                 # саморезы 4×16: верхние плечи опор — столешница
        for y in (YF[0] + 60, YF[1] - 120):
            d.polyline([(x, y, Z_TOP), (x, y, Z_TOP + up)], ax, 0.5)
    for x0, x1 in TUMBA:                                 # тумбы — на место между опорами
        xc = (x0 + x1) / 2
        d.polyline([(xc, YT[0] - 420 + 547, 450), (xc, YT[1] - 20, 450)], ax, 0.5)
    d.polyline([(900, YC[1] + 260, 450), (900, YC[1], 450)], ax, 0.5)
    d.polyline([(8, 680, H + up), (8 - 200, 680, H + up + 120)], ax, 0.5)
    d.polyline([(L - 8, 680, H + up), (L - 8 + 200, 680, H + up + 120)], ax, 0.5)
    d.polyline([(900, D - 8, H + up), (900, D - 8, H + up + 170)], ax, 0.5)
    sx, sy = (SINK[0] + SINK[1]) / 2, (SINK[2] + SINK[3]) / 2
    if chem:
        d.polyline([(sx, sy, H + up), (sx, sy, H + up + 150)], ax, 0.5)
        d.polyline([(MIX[0], MIX[1], H + up), (MIX[0], MIX[1], H + up + 470)], ax, 0.5)
    else:
        d.polyline([(800, PANEL[3] - 420, 780), (800, PANEL[3] - 10, 780)], ax, 0.5)
        # провод поз. 9 в гофротрубе (невидимый контур): от щитка за панелью вниз к полу
        xg = SHIELD[1] - 20
        d.polyline([(xg, PANEL[3] - 412, SHIELD[4]), (xg, PANEL[3] - 412, 0)], True, 0.8)
    for (x0, x1) in SUP:                                 # опоры М8 через кронштейны в плечи
        for yo in YO:
            d.polyline([((x0 + x1) / 2, yo, Z_FOOT), ((x0 + x1) / 2, yo, -92)], ax, 0.5)
    d.callout(1, (1745, 400, Z_FOOT + 30), (10, -4))
    # полка — в свободном поле слева, не на бортике (у поз. 1 сверху слева мойка и смеситель — ниже кромки)
    d.callout(2, (400, 60, H + up), (-20, -8)) if chem else d.callout(2, (480, 430, H + up), (-24, 9))
    d.callout(3, (300, YT[0] - 436, 400), (-12, -6))
    d.callout(4, (1488, YT[0] - 436, 380), (-8, -14))
    d.callout(5, (SUP[1][0] - 1, YC[1] + 260, 450), (12, 6))
    if chem:
        d.callout(6, (SINK[1] + 6, sy, H + up + 303), (-16, 6))
        d.callout(7, (MIX[0], MIX[1], H + up + 470 + 170), (-10, 6))
        nf, nb = 8, 9
    else:
        d.callout(6, (620, PANEL[2] - 420, 840), (-8, 22))
        d.callout(7, ((SHIELD[0] + SHIELD[1]) / 2, SHIELD[2] - 420, (SHIELD[4] + SHIELD[5]) / 2), (-8, -18))
        d.callout(8, ((SOCKET[0] + SOCKET[1]) / 2, SOCKET[2] - 420, 750), (-16, -10))
        d.callout(9, (SHIELD[1] - 20, PANEL[3] - 412, 300), (-12, -10))
        nf, nb = 10, 11
    d.callout("М8×16", (SUP[1][0], YP[1] - 15, Z_TOP - 30), (16, 4))
    d.callout("4×16", (70, YF[0] + 60, Z_TOP + 300), (-14, 4))
    d.callout(nf, (1730, YO[0], -96), (10, -4))
    d.callout(nb, (1700, YO[1] - 12, -49), (16, -2))
    return d


WATER_POZ1 = {"mixer": "7", "sink": "6", "siphon": "сифон", "hose": "G1/2\"",
              "legend": ("6 – мойка 300×150", "7 – смеситель", "     двухрожковый")}


def water(path, poz=WATER_POZ1):
    """Схема подключения мойки и смесителя к водопроводу (Т3, В1) и канализации (К1), обозначения
    трубопроводов по ГОСТ 21.601; краны и трубопроводы — сети здания. poz — номера позиций и легенда изделия."""
    s = Sheet(116, 88)

    def lead(x, y, xt, yt, label, left=False):
        """Выноска: точка на элементе, наклонная линия и полка с надписью."""
        s.dot(x, y, 0.9)
        w = s.text_w(label, 3.0) + 1.0
        x2 = xt - w if left else xt + w
        s.line([(x, y), (xt, yt), (x2, yt)], 0.18)
        s.text(min(xt, x2) + 0.5, yt - 0.8, label, 3.0)

    zt = 28                                            # верх столешницы
    s.line([(4, zt), (82, zt)], 0.5)
    s.line([(4, zt + 2.4), (82, zt + 2.4)], 0.25)
    # мойка (разрез) с выпуском
    s.line([(20, zt), (22, zt + 15), (42, zt + 15), (44, zt)], 0.5)
    s.line([(32, zt + 15), (32, zt + 20)], 0.5)
    # смеситель: корпус, излив, вентили
    s.rect(53, zt - 4, 59, zt, 0.35)
    s.line([(56, zt - 4), (56, zt - 18), (36, zt - 18), (36, zt - 11)], 0.5)
    s.line([(50, zt - 2.5), (53, zt - 2.5)], 0.35)
    s.line([(59, zt - 2.5), (62, zt - 2.5)], 0.35)
    # гибкие подводки и запорные краны
    for x0, xe, name in ((55, 66, "Т3"), (57, 74, "В1")):
        s.line([(x0, zt), (x0, zt + 18), (xe, zt + 24), (xe, zt + 32)], 0.35, dash=(1.6, 0.8))
        y = zt + 32
        s.line([(xe - 1.5, y), (xe + 1.5, y + 3), (xe + 1.5, y), (xe - 1.5, y + 3), (xe - 1.5, y)], 0.35)
        s.line([(xe, y + 3), (xe, zt + 43)], 0.6)
        s.text(xe - 1.8, zt + 47, name, 3.0)
    # сифон и гофрошланг к канализации
    s.line([(32, zt + 20), (32, zt + 24)], 0.5)
    s.rect(29, zt + 24, 35, zt + 34, 0.35)
    s.line([(35, zt + 29), (41, zt + 29), (44, zt + 33), (44, zt + 36)], 0.5, dash=(1.6, 0.8))
    s.line([(41, zt + 36), (47, zt + 36), (47, zt + 43), (41, zt + 43), (41, zt + 36)], 0.5)
    s.text(42, zt + 47, "К1", 3.0)
    # позиции
    lead(56, zt - 12, 66, zt - 22, poz["mixer"])
    lead(42, zt + 6, 12, zt + 10, poz["sink"], left=True)
    lead(29, zt + 30, 12, zt + 26, poz["siphon"], left=True)
    lead(70, zt + 18 + 6 * 13 / 17, 80, zt + 31, poz["hose"])      # на подводке В1
    # условные обозначения
    x, y = 86, 14
    legend = poz["legend"] + ("Т3 – горячая вода", "В1 – холодная вода", "К1 – канализация", "     Ø50")
    if poz["hose"].startswith("G"):
        legend += ("G1/2\" – подводка", "     гибкая, 2 шт.")
    for t in legend:
        s.text(x, y, t, 2.7)
        y += 4.4
    s.text(4, 83, "Запорные краны G1/2\", трубопроводы Т3, В1 и К1 – сети здания,", 2.6)
    s.text(4, 87, "в комплект поставки не входят.", 2.6)
    s.save(path)
    return path


PALETTE = {"опора": LEGS, "перемычка": LEGS, "кронштейн": LEGS, "опора регулируемая": (45, 45, 45),
           "ножка": (45, 45, 45), "тумба": (206, 206, 202), "дверца": (214, 214, 210), "царга": (206, 206, 202),
           "ручка": (150, 152, 156), "столешница": (222, 222, 219), "бортик продольный": (190, 190, 187),
           "бортик боковой": (190, 190, 187), "мойка": (242, 242, 242), "смеситель": (170, 172, 176),
           "панель передняя": (206, 206, 202), "щиток": (236, 236, 236), "розетка двойная": (242, 242, 242)}


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "out"
    os.makedirs(out, exist_ok=True)
    for key, chem in (("01", True), ("02", False)):
        d = general(chem)
        print(d.render(os.path.join(out, f"{key}_рис1_общий_вид.png")))
        print(mounting(chem).render(os.path.join(out, f"{key}_рис2_схема_монтажа.png")))
        d.w_mm, d.h_mm = 67, 56           # рамка изображения на обложке
        print(d.render(os.path.join(out, f"{key}_обложка.png"), palette=PALETTE))
    print(water(os.path.join(out, "01_рис3_подключение_мойки.png")))


if __name__ == "__main__":
    main()
