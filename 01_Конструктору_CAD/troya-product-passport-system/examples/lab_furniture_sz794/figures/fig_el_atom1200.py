# -*- coding: utf-8 -*-
"""Схема электрическая принципиальная: стол «Атом» 1200 для кабинета физики (поз. 5) и стол демонстрационный
для кабинета физики (поз. 2, провод 5 м, розетка с крышкой) — состав электрики по схемам сборки одинаковый.
Состав — по схеме сборки 03_Корпус (24.10.2026): щиток на 4 модуля, дифавтомат, шина на DIN-изоляторе,
розетка накладная двойная, провод ПВС 3×2,5 – 3 м в гофротрубе (ввод через опору и линия к розетке).
Шина показана как шина PE: N проходит через двухполюсный дифавтомат (подтверждает конструктор).
Запуск: python -P fig_el_atom1200.py <папка вывода>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sch import DASH, DASH_DOT, W_THIN, Sheet

L_, N_, PE_ = 18, 28, 38          # ряды проводников L, N, PE


def scheme(cable="3 м", socket="Розетка накладная двойная с заземляющим контактом, 16 А, 250 В"):
    s = Sheet(116, 100)
    # ввод от групповой линии (в комплект не входит)
    for y, name in ((L_, "L"), (N_, "N"), (PE_, "PE")):
        s.line([(6, y), (37 if y != PE_ else 56, y)])
        s.text(1.5, y + 1.2, name, 3.5)
    s.text(1.5, 46, "~220 В", 3.0)
    s.text(1.5, 50, "50 Гц", 3.0)

    # A1 — щиток
    s.rect(22, 6, 68, 50, dash=DASH_DOT)
    s.text(22, 4.6, "A1", 3.5)

    # QFD1 — дифавтомат: трансформатор тока, расцепитель IΔ, два полюса
    s.ellipse(28, 23, 1.6, 7.5)
    s.rect(25.5, 8, 30.5, 13, w=0.35)
    s.text(28, 10.6, "IΔ", 3.0, anchor="mm")
    s.line([(28, 13), (28, 15.5)])
    mids = [s.breaker_pole(37, y) for y in (L_, N_)]
    xm = mids[0][0]
    s.line([(30.5, 10.5), (xm, 10.5), (xm, mids[1][1])], W_THIN, DASH)
    s.text(46, 11, "QFD1", 3.5)
    s.text(46, 15, "16 А, 30 мА", 3.0)

    # шины N и PE
    s.line([(44, L_), (98, L_)])
    s.line([(44, N_), (103, N_)])
    s.line([(56, PE_), (108, PE_)])
    s.line([(56, PE_ - 2.2), (56, PE_ + 2.2)], 0.8)
    s.text(58, PE_ + 6, "XPE", 3.0)

    # W1 — ввод (через опору к полу), W2 — к розетке; провод ПВС 3×2,5 в гофротрубе
    s.cable_tick(14, L_, PE_, "W1")
    s.cable_tick(73, L_, PE_, "W2")

    # XS1, XS2 — розетка двойная
    for xs, name, last in ((80, "XS1", False), (98, "XS2", True)):
        for i, y in enumerate((L_, N_, PE_)):
            x = xs + 5 * i
            if not last:
                s.dot(x, y)
            s.line([(x, y), (x, 46)])
            s.socket_down(x, 46)
        s.rect(xs - 2.5, 43.5, xs + 12.5, 51.5, dash=DASH_DOT)
        s.text(xs + 5, 55.5, name, 3.5, anchor="ms")
        for i, t in enumerate(("L", "N", "PE")):
            s.text(xs + 5 * i, 50.6, t, 2.0, anchor="ms")

    s.parts_list(1, 62, [
        ("A1", "Щиток на 4 модуля", "1", ""),
        ("QFD1", "Выключатель автоматический дифференциального тока 2P (1P+N), 16 А, 30 мА", "1", ""),
        ("XPE", "Шина нулевая на DIN-изоляторе (защитная PE)", "1", "в A1"),
        ("W1, W2", "Провод ПВС 3×2,5 мм² в гофротрубе Ø16 мм", cable, ""),
        ("XS1, XS2", socket, "1", "2 гн."),
    ])
    return s


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "out"
    os.makedirs(out, exist_ok=True)
    print(scheme().save(os.path.join(out, "05_рис3_схема_электрическая.png")))
    print(scheme("5 м", "Розетка накладная двойная с крышкой, с заземляющим контактом, 16 А, 250 В")
          .save(os.path.join(out, "02_рис3_схема_электрическая.png")))


if __name__ == "__main__":
    main()
