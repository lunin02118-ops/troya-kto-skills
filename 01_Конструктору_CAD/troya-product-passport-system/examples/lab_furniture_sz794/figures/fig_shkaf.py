def disc(cx, cy, r, z0, h, name, pat=None, line=1.0, n=32):
    """Цилиндр с вертикальной осью."""
    pts = [(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n), z0) for i in range(n)]
    return extrude(pts, (0, 0, h), name, pat, line, smooth=True)


def frame_x(x0, x1, y0, y1, z0, z1, w, name):
    """Рама из профиля в вертикальной плоскости, параллельной оси x (стекло не рисуется)."""
    return [box(x0, y0, z0, x0 + w, y1, z1, name), box(x1 - w, y0, z0, x1, y1, z1, name),
            box(x0 + w, y0, z0, x1 - w, y1, z0 + w, name), box(x0 + w, y0, z1 - w, x1 - w, y1, z1, name)]


def frame_y(x0, x1, y0, y1, z0, z1, w, name):
    """Рама из профиля в вертикальной плоскости, параллельной оси y."""
    return [box(x0, y0, z0, x1, y0 + w, z1, name), box(x0, y1 - w, z0, x1, y1, z1, name),
            box(x0, y0 + w, z0, x1, y1 - w, z0 + w, name), box(x0, y0 + w, z1 - w, x1, y1 - w, z1, name)]


def sash(z0):
    """Створка 759×550 в алюминиевом профиле: нижняя планка с ручкой, боковые профили-ручки, верхняя планка."""
    x0, x1 = SASH_W
    y0, y1 = SASH_Y
    z1 = z0 + SASH_H
    return [box(x0, y0, z0, x1, y1, z0 + 50, "створка"), box(x0, y0, z1 - 40, x1, y1, z1, "створка"),
            box(x0, y0, z0 + 50, x0 + 30, y1, z1 - 40, "створка"), box(x1 - 30, y0, z0 + 50, x1, y1, z1 - 40, "створка"),
            box(x0 + 10, y0 - 14, z0 + 6, x1 - 10, y0, z0 + 30, "ручка", line=0.7)]       # профиль-ручка во всю ширину


def worktop_top():
    """Узор верха столешницы: борт и чаша мойки-слива, выпуск."""
    x0, x1, y0, y1 = SINK
    k = SINK_IN
    return (rect_lines(x0, x1, y0, y1, H) + rect_lines(x0 + k, x1 - k, y0 + k, y1 - k, H)
            + [("dot", ((x0 + x1) / 2, (y0 + y1) / 2, H), 9)])


def panel_face():
    """Лицевая сторона рамки: клавиша выключателя (слева) и две розетки с крышками."""
    x0, x1, _, y, z0, z1 = PANEL
    zc, w = (z0 + z1) / 2, (x1 - x0) / 3
    pat = [("l", (x0 + w * i, y - 6, z0), (x0 + w * i, y - 6, z1)) for i in (1, 2)]
    for i in (1, 2):
        pat += ring((x0 + w * (i + 0.5), y - 6, zc), 20, "y")
    xs = x0 + w * 0.5
    pat += rect_lines_y(xs - 12, xs + 12, zc - 18, zc + 18, y - 6)
    return pat


def rect_lines_y(x0, x1, z0, z1, y):
    p = [(x0, y, z0), (x1, y, z0), (x1, y, z1), (x0, y, z1)]
    return [("l", p[i], p[(i + 1) % 4]) for i in range(4)]


def parts(sash_z=H + 250):
    g = {k: [] for k in ("feet", "frame", "corpus", "doors", "shelf", "top", "sink", "mixer", "stand_f", "stand_r",
                         "rear", "side_l", "side_r", "front", "sash", "roof", "lamp")}
    for x, y in LEGS_XY:
        g["feet"].append(box(x, y, 0, x + 40, y + 40, Z_FOOT, "ножка", line=0.8))
    f = g["frame"]                    # основание — корпус из ЛДСП: боковины, дно, задняя стенка, передняя панель
    f += [box(0, 0, Z_FOOT, LD, D, Z_TOP, "корпус"), box(L - LD, 0, Z_FOOT, L, D, Z_TOP, "корпус"),
          box(LD, 0, Z_FOOT, L - LD, D, Z_FOOT + LD, "корпус"),
          box(LD, D - LD, Z_FOOT + LD, L - LD, D, Z_TOP, "корпус"),
          box(LD, 0, Z_APRON, L - LD, LD, Z_TOP, "панель передняя")]
    x0, x1, _, _, z0, z1 = PANEL
    f.append(box(x0, -6, z0, x1, 0, z1, "рамка розеток", {"front": panel_face()}, line=0.8))
    for dx0, dx1 in ((2, L / 2 - 1), (L / 2 + 1, L - 2)):                 # дверцы накладные
        xh = dx1 - 60 if dx0 < L / 2 else dx0 + 60           # ручки врезные круглые — вверху у притвора
        handle = ring((xh, -16, Z_APRON - 90), 26, "y") + ring((xh, -16, Z_APRON - 90), 17, "y")
        g["doors"].append(box(dx0, -16, Z_FOOT + 2, dx1, 0, Z_APRON - 2, "дверца", {"front": handle}))
    g["shelf"].append(box(LD + 2, 20, 420, L - LD - 2, D - LD - 10, 436, "полка"))
    g["top"].append(box(0, 0, Z_TOP, L, D, H, "столешница", {"top": worktop_top()}))
    sx0, sx1, sy0, sy1 = SINK
    k = SINK_IN
    g["sink"].append(box(sx0 + k, sy0 + k, H - 150, sx1 - k, sy1 - k, Z_TOP, "мойка", line=0.8))
    g["mixer"] += mixer(MIX[0], MIX[1], H)
    for x in (0, L - 60):
        g["stand_f"].append(box(x, 0, H, x + 60, 60, Z_CH, "стойка передняя"))
    for x in (0, L - 30):
        g["stand_r"].append(box(x, D - 60, H, x + 30, D, Z_CH, "стойка задняя"))
    g["rear"] += frame_x(30, L - 30, D - 16, D, H, Z_CH, 46, "рама")
    g["side_l"] += frame_y(22, 38, 60, D - 60, H, Z_CH, 40, "рама")
    g["side_r"] += frame_y(L - 38, L - 22, 60, D - 60, H, Z_CH, 40, "рама")
    g["front"] += frame_x(60, L - 60, 6, 22, FIX_Z, Z_CH, 40, "рама")
    g["sash"] += sash(sash_z)
    g["roof"].append(box(0, 0, Z_CH, L, D, Z_ROOF, "панель верхняя"))
    g["roof"].append(disc(DUCT[0], DUCT[1], DUCT[2], Z_ROOF, 60, "патрубок", ring((DUCT[0], DUCT[1], Z_ROOF + 60), 55)))
    g["lamp"].append(box(150, 70, Z_CH - 70, 750, 146, Z_CH - 4, "светильник", line=0.8))
    return g


def glass(d, plane, u0, v0, size=70, n=3, gap=22):
    """Условное обозначение стекла: группа параллельных коротких штрихов под 45°. plane(u, v) -> точка 3D."""
    for i in range(n):
        o = i * gap
        d.polyline([plane(u0 + o, v0), plane(u0 + o + size, v0 + size)], False, 0.45)


def glass_marks(d, off=None, sash_z=H + 250):
    off = off or {}
    def sh(key, p):
        v = off.get(key, (0, 0, 0))
        return (p[0] + v[0], p[1] + v[1], p[2] + v[2])
    glass(d, lambda u, v: sh("side_r", (L - 30, u, v)), 200, 1350)
    glass(d, lambda u, v: sh("front", (u, 14, v)), 520, FIX_Z + 120)
    glass(d, lambda u, v: sh("sash", (u, 43, v)), 520, sash_z + 120)


def general():
    g = parts()
    d = Drawing(116, 98, view="спереди-справа")
    for k, items in g.items():
        if k not in ("shelf", "sink"):
            d.add(*items)
    glass_marks(d)
    d.callout(1, (L, 330, 500), (14, -6))
    d.callout(2, (L - 22, 300, Z_CH - 20), (14, 6))
    return d


LOWER = ("feet", "frame", "doors", "shelf")        # нижняя часть поз. 1; остальное — верхняя часть поз. 2
ECC = ((LD / 2, 100), (LD / 2, D - 100), (L - LD / 2, 100), (L - LD / 2, D - 100),   # стяжки: боковины,
       (250, D - LD / 2), (L - 250, D - LD / 2))                                    # задняя стенка


def mounting():
    """Рисунок 2: верхняя часть (рабочая камера со столешницей) поднята над нижней (основание без столешницы)."""
    g = parts()
    up = 300
    d = Drawing(116, 78, view="спереди-справа")    # помещается под п. 4.2.2
    for k, items in g.items():
        if k == "shelf":                           # за дверцами не видна
            continue
        d.add(*[translate(s, (0, 0, 0 if k in LOWER else up)) for s in items])
    glass_marks(d, {k: (0, 0, up) for k in ("side_r", "front", "sash")})
    # соединение частей — как в модели bCAD: штоки стяжек эксцентриковых и шканты в нижней плоскости столешницы
    # входят в торцы боковин и задней стенки основания (по 2 в каждой)
    z = Z_TOP + up
    for (x, y), (dx, dy) in zip(ECC, ((0, 40), (0, -40), (0, 40), (0, -40), (40, 0), (-40, 0))):
        d.polyline([(x, y, z), (x, y, z - 60)], False, 1.8)    # шток эксцентрика (условно, увеличен)
        d.polyline([(x + dx, y + dy, z), (x + dx, y + dy, z - 30)], False, 1.4)  # шкант
        d.polyline([(x, y, z - 60), (x, y, Z_TOP)], "dashdot", 0.5)
    d.callout(1, (L, 330, 500), (14, -6))
    d.callout(2, (L - 22, 300, Z_CH - 20 + up), (14, 6))
    d.callout("эксцентрик", (LD / 2, 100, z - 60), (-12, -5))
    d.callout("шкант", (LD / 2, 140, z - 30), (-12, 5))
    return d


def connections(path):
    """Схема подключения: водопровод Т3, В1 и канализация К1 (ГОСТ 21.601), ввод питания, вытяжная вентиляция.
    Шкаф — упрощённо, вид спереди, масштаб 1:30; сети здания — справа."""
    s = Sheet(116, 100)
    k = 1 / 30

    def lead(x, y, xt, yt, label, left=False):
        """Выноска; у левой полки xt — её правый конец, полка не выходит за край листа."""
        s.dot(x, y, 0.9)
        w = s.text_w(label, 3.0) + 1.0
        if left:
            xt = max(xt, w + 1.5)
        x2 = xt - w if left else xt + w
        s.line([(x, y), (xt, yt), (x2, yt)], 0.18)
        s.text(min(xt, x2) + 0.5, yt - 0.8, label, 3.0)

    fl = 92                                   # пол
    x0 = 12
    X = lambda mm: x0 + mm * k
    Y = lambda mm: fl - mm * k
    s.line([(4, fl), (70, fl)], 0.5)
    # основание, столешница, рабочая камера, панель верхняя, патрубок
    s.rect(X(0), Y(Z_TOP), X(L), Y(Z_FOOT), 0.35)
    s.line([(X(L / 2), Y(Z_APRON)), (X(L / 2), Y(Z_FOOT))], 0.25)
    s.line([(X(0), Y(Z_APRON)), (X(L), Y(Z_APRON))], 0.25)
    for xf in (20, L - 60):                                              # ножки 40×40×70
        s.rect(X(xf), Y(Z_FOOT), X(xf + 40), fl, 0.25)
    s.rect(X(-5), Y(H), X(L + 5), Y(Z_TOP), 0.5)
    s.rect(X(0), Y(Z_CH), X(60), Y(H), 0.35)
    s.rect(X(L - 60), Y(Z_CH), X(L), Y(H), 0.35)
    s.rect(X(0), Y(Z_ROOF), X(L), Y(Z_CH), 0.5)
    s.rect(X(70), Y(H + SASH_H), X(830), Y(H), 0.25)                    # створка (опущена)
    s.line([(X(60), Y(FIX_Z)), (X(L - 60), Y(FIX_Z))], 0.25)
    xd = X(DUCT[0])
    s.rect(xd - 62.5 * k, Y(Z_ROOF + 60), xd + 62.5 * k, Y(Z_ROOF), 0.35)
    # воздуховод с вентилятором канальным до сети вентиляции
