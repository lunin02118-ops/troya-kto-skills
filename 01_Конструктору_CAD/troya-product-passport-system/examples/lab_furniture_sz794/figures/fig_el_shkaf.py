# -*- coding: utf-8 -*-
"""Схема электрическая принципиальная шкафа вытяжного демонстрационного ШВ.LG.0001 (поз. 8).
Состав — по схеме сборки «Шкаф вытяжной (серый) 900х640х2087» (24.10.2026) и ответам пользователя: щиток на 4 модуля
с АВДТ 16 А, 30 мА и нулевой шиной на левой стенке основания; рамка на 3 модуля слева на передней панели —
выключатель (включает светильник и вентилятор одновременно) и две розетки с крышками IP54; светильник LED 18 Вт
и канальный вентилятор MARS GDF 100 (62 Вт) в верхней части, которые при сборке подключают клеммами X1;
провод ПВСг 3×2,5 в гофротрубе. Кабель ввода в комплект не входит.
Запуск: python -P fig_el_shkaf.py <папка вывода>
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sch import DASH, DASH_DOT, W_THIN, Sheet

L_, N_, PE_ = 18, 28, 38          # ряды проводников L, N, PE
L1_, N1_, PE1_ = 69, 73, 77       # линии верхней части: L1 (после выключателя), N, PE
X_SA, X_N, X_PE = 97, 114, 110    # спуски к клеммам X1: L1 через SA1, N и PE (N правее — без пересечения с PE)
Y_X1 = 65                         # клеммы X1


def switch_down(s, x, y0, y1):
    """Контакт выключателя замыкающий (ГОСТ 2.755) в вертикальной цепи: провод приходит сверху в (x, y0)."""
    s.line([(x, y0), (x + 3.4, y0 + 6.0)])
    s.line([(x, y0 + 7.0), (x, y1)])


def load(s, x, kind, name):
    """Приёмник между линиями L1, N с корпусом на PE: выводы в x (L1), x + 4 (N), x + 8 (PE)."""
    cx, cy, r = x + 2, 82, 3.0
    for xt, y in ((x, L1_), (x + 4, N1_)):
        s.dot(xt, y)
        s.line([(xt, y), (xt, cy - math.sqrt(r * r - (xt - cx) ** 2))])
    s.dot(x + 8, PE1_)
    s.line([(x + 8, PE1_), (x + 8, cy), (cx + r, cy)], W_THIN)
    s.ellipse(cx, cy, r, r)
    if kind == "lamp":                         # светильник (ГОСТ 2.732): круг с крестом
        k = r / math.sqrt(2)
        s.line([(cx - k, cy - k), (cx + k, cy + k)], W_THIN)
        s.line([(cx - k, cy + k), (cx + k, cy - k)], W_THIN)
    else:                                      # электродвигатель (ГОСТ 2.722)
        s.text(cx, cy, "M", 3.2, anchor="mm")
    s.text(cx, 90.3, name, 3.5, anchor="ms")


def scheme():
    s = Sheet(116, 137)
    # ввод от групповой линии (кабель ввода в комплект не входит)
    for y, name in ((L_, "L"), (N_, "N"), (PE_, "PE")):
        s.line([(6, y), (37 if y != PE_ else 64, y)])
        s.text(1.5, y + 1.2, name, 3.5)
    s.text(1.5, 46, "~230 В", 3.0)
    s.text(1.5, 50, "50 Гц", 3.0)
    s.cable_tick(14, L_, PE_, "W1")

    # A1 — щиток с дифавтоматом QFD1 (левая стенка основания)
    s.rect(22, 6, 62, 46, dash=DASH_DOT)
    s.text(22, 4.6, "A1", 3.5)
    s.ellipse(28, 23, 1.6, 7.5)
    s.rect(25.5, 8, 30.5, 13, w=0.35)
    s.text(28, 10.6, "IΔ", 3.0, anchor="mm")
    s.line([(28, 13), (28, 15.5)])
    mids = [s.breaker_pole(37, y) for y in (L_, N_)]
    xm = mids[0][0]
    s.line([(30.5, 10.5), (xm, 10.5), (xm, mids[1][1])], W_THIN, DASH)
    s.text(45, 11, "QFD1", 3.5)
    s.text(45, 15, "16 А, 30 мА", 3.0)

    # линии после дифавтомата
    s.line([(44, L_), (X_SA, L_), (X_SA, 44)])
    s.line([(44, N_), (X_N, N_), (X_N, Y_X1)])
    s.line([(64, PE_), (X_PE, PE_), (X_PE, Y_X1)])
    s.cable_tick(65, L_, PE_, "W2")

    # A2 — рамка на передней панели: розетки XS1, XS2 и выключатель SA1
    s.rect(67.5, 41.5, 107.5, 57.5, dash=DASH_DOT)
    s.text(61.5, 57, "A2", 3.5)
    for xs, name in ((70, "XS1"), (83, "XS2")):
        for i, y in enumerate((L_, N_, PE_)):
            x = xs + 4.5 * i
            s.dot(x, y)
            s.line([(x, y), (x, 46)])
            s.socket_down(x, 46)
        s.text(xs + 4.5, 55.5, name, 3.5, anchor="ms")
        for i, t in enumerate(("L", "N", "PE")):
            s.text(xs + 4.5 * i, 50.6, t, 2.0, anchor="ms")
    switch_down(s, X_SA, 44, Y_X1)
    s.text(100.8, 47.6, "SA1", 3.2)

    # X1 — клеммы соединения частей шкафа (подключаются при сборке)
    s.rect(89.5, Y_X1 - 2.5, 115.5, Y_X1 + 2.5, dash=DASH_DOT)
    s.text(90.3, Y_X1 + 1.2, "X1", 3.2)
    for x in (X_SA, X_PE, X_N):
        s.ellipse(x, Y_X1, 0.8, 0.8, W_THIN)

    # линии верхней части: L1, N, PE — влево к светильнику и вентилятору
    s.line([(X_SA, Y_X1 + 0.8), (X_SA, L1_), (70, L1_)])
    s.line([(X_N, Y_X1 + 0.8), (X_N, N1_), (74, N1_)])
    s.line([(X_PE, Y_X1 + 0.8), (X_PE, PE1_), (78, PE1_)])
    s.line([(91.8, PE1_ + 2.2), (94.2, L1_ - 1.6)], W_THIN)     # жгут W3
    s.text(93.5, 83, "W3", 3.5)
    load(s, 70, "lamp", "EL1")
    load(s, 82, "motor", "M1")

    s.parts_list(1, 92, [
        ("A1", "Щиток на 4 модуля с нулевой шиной", "1", ""),
        ("QFD1", "Выключатель дифф. тока (АВДТ) 1P+N, 16 А, 30 мА", "1", ""),
        ("A2", "Рамка на 3 модуля (передняя панель основания)", "1", ""),
        ("SA1", "Выключатель модульный (светильник и вентилятор)", "1", ""),
        ("XS1, XS2", "Розетка модульная с заземлением и крышкой, IP54", "2", ""),
        ("X1", "Клеммы соединительные (соединение частей шкафа)", "1 к-т", ""),
        ("EL1", "Светильник светодиодный IP65, 18 Вт", "1", ""),
        ("M1", "Вентилятор канальный Ø100 мм, 62 Вт", "1", ""),
        ("W2, W3", "Провод ПВСг 3×2,5 мм² в гофротрубе Ø16 мм", "1 к-т", ""),
        ("W1", "Кабель ввода от сети здания", "–", "не вх."),
    ], size=2.7, row_h=4.0)
    return s


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "out"
    os.makedirs(out, exist_ok=True)
    print(scheme().save(os.path.join(out, "08_рис3_схема_электрическая.png")))


if __name__ == "__main__":
    main()
