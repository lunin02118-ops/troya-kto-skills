def assembly(d, pr):
    d.section(pr.get("assembly_title", "Сборка и монтаж изделия"))
    d.subsection("Общие указания")
    for t in pr.get("assembly_general", []):
        d.text(t)
    d.text("Операции, выполненные на предприятии-изготовителе (в зависимости от состава упаковочных мест), "
           "при сборке пропускаются.")
    sealant = "water" in pr.get("connections", [])
    d.text("Сборку выполнять вдвоём на ровном чистом полу, подложив под детали мягкий материал (картон, ткань), "
           "чтобы не повредить облицовку. Перед сборкой проверить комплектность по разделу 3 и снять "
           "транспортировочную плёнку. Для сборки потребуются: набор шестигранных ключей, отвёртка (шуруповёрт) "
           "с битой PH2, строительный уровень" + (", а также санитарный силиконовый герметик." if sealant else "."))
    if sealant:
        d.text("Герметик в комплект поставки изделия не входит. При поставке крупной партии он, как правило, "
               "поставляется на весь заказ; при поставке единичного изделия герметик приобретает монтажная "
               "организация.")
    if pr.get("cold_note", True):
        d.text("Изделие, транспортированное или хранившееся при отрицательной температуре, перед распаковкой "
               "и сборкой следует выдержать в помещении не менее 24 ч.")
    d.subsection("Порядок сборки")
    k = 0
    for step in pr["assembly"]:
        if isinstance(step, tuple) and step[0] == "fig":
            d.figure(step[1], step[2], min(step[3] if len(step) > 3 else 4.5, 4.5), image=img(pr, step[1]))
        else:
            k += 1
            d.text(f"{d.sec_no}.{d.item_no}.{k}. {step}", first=426)
    for block in pr.get("connections", []):
        CONNECTIONS[block](d, pr)


