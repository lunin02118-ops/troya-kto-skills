def transport(d, pr):
    d.section("Транспортирование и хранение")
    d.item("Изделие транспортируют в упаковке изготовителя всеми видами транспорта в крытых транспортных "
           "средствах или контейнерах в соответствии с правилами перевозки грузов, действующими на данном виде "
           "транспорта (ГОСТ 16371-2014, п. 8.1, 8.2), с защитой от атмосферных осадков, загрязнения и "
           "механических повреждений. Дверцы и ящики на время транспортирования фиксируют от открывания.")
    fragile = pr.get("fragile")
    d.item("При погрузке и выгрузке не допускаются удары и падения упаковок. "
           + (f"Упаковки с {fragile} маркируют манипуляционными знаками «Хрупкое. Осторожно» и «Верх» и "
              "перевозят в положении, указанном знаком." if fragile else
              "Упаковки укладывают так, чтобы исключить их перемещение при транспортировании."))
    d.item("Изделие хранят в упаковке в крытых помещениях при температуре не ниже +2 °С и относительной "
           "влажности воздуха от 45 % до 70 % (ГОСТ 16371-2014, п. 8.3), на расстоянии не менее 1,5 м от "
           "отопительных приборов, на поддонах или стеллажах, исключающих контакт с полом.")


def disposal(d, pr):
    d.section("Сведения об утилизации")
    d.item(f"По истечении срока службы изделие подлежит утилизации. Перед демонтажем изделие "
           + ("отключают от электросети" if "power" in pr.get("connections", []) else "")
           + (" и " if ("power" in pr.get("connections", []) and "water" in pr.get("connections", [])) else "")
           + ("отсоединяют от водопровода и канализации" if "water" in pr.get("connections", []) else "")
           + ("освобождают от предметов и материалов" if not pr.get("connections") else "")
           + ".")
    d.item("Изделие разбирают и сортируют по видам материалов: металлические детали – лом чёрных металлов; "
           "детали из ДСП и ЛДСП – отходы древесных плит; пластмассовые детали"
           + (", органическое стекло" if pr.get("plexi") else "")
           + " – отходы пластмасс"
           + ("; алюминиевые профили – лом цветных металлов" if pr.get("alu") else "")
           + ("; керамические изделия – строительные отходы" if pr.get("ceramic") else "") + ".")
    if "power" in pr.get("connections", []) or pr.get("electro"):
        d.item(f"Электротехнические изделия ({pr['electro_list']}) утилизируют как отходы электрического и "
               "электронного оборудования; выбрасывать их вместе с бытовыми отходами не допускается.")
    d.item("Утилизацию проводят в соответствии с законодательством об отходах производства и потребления "
           "государства, на территории которого эксплуатируется изделие (в Российской Федерации – Федеральный "
           "закон № 89-ФЗ «Об отходах производства и потребления», в Республике Казахстан – Экологический "
           "кодекс Республики Казахстан).")


