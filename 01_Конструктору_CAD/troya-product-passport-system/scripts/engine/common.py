def img(pr, key):
    """PNG рисунка из figures\out по ключу pr["images"] (подпись рисунка, "general" или "cover"); None — рамка."""
    name = pr.get("images", {}).get(key)
    if name and os.path.exists(os.path.join(FIG_OUT, name)):
        return os.path.join(FIG_OUT, name)
    return None


