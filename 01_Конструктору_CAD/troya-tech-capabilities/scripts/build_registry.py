SKIP_OTHER = "15 Прочее (не технологическое)"


def read_os(path):
    import xlrd
    book = xlrd.open_workbook(str(path))
    sh = book.sheet_by_index(0)
    items = []
    started = False
    for r in range(sh.nrows):
        name = str(sh.cell_value(r, 0)).strip()
        if name == "Головное подразделение":
            started = True
            continue
        if not started or not name:
            continue
        items.append(name)
    return items


def classify(name):
    for rx, grp, kind, short, spec, cnc, status, src in RULES:
        if re.search(rx, name):
            return dict(group=grp, kind=kind, short=short, spec=spec, cnc=cnc, status=status, source=src)
    return dict(group=SKIP_OTHER, kind="", short=name, spec="", cnc="", status=O, source="ОС.xls")


def build(os_path):
    rows = OrderedDict()
    for name in read_os(os_path):
        c = classify(name)
        # оснастку и пресс-формы не схлопываем — у каждой своя деталь/размер
        if c["kind"] in ("Оснастка трубогиба", "Пресс-форма (собственная)"):
            key = name
            c["short"] = name
        else:
            key = (c["group"], c["short"])
        if key in rows:
            rows[key]["qty"] += 1
            rows[key]["os_names"].append(name)
        else:
            rows[key] = dict(c, qty=1, os_names=[name])
    out = sorted(rows.values(), key=lambda x: (x["group"], x["kind"], x["short"]))
    return out


def write_csv(rows, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
